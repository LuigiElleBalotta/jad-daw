#!/usr/bin/env node
// Writes docs/shortcuts-check.md from ui/actions/actions.json: one table per menu with our default shortcut for every
// action that has one, so the defaults can be compared with Logic Pro's own Key Commands window (Option-K).
// Usage: node tools/gen-shortcut-checklist.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const actions = JSON.parse(readFileSync(resolve(root, "ui/actions/actions.json"), "utf8"));

const byMenu = new Map();
for (const a of actions) {
  if (!a.shortcut) continue;
  const top = a.menu.split("/")[0] || "(no menu)";
  if (!byMenu.has(top)) byMenu.set(top, []);
  byMenu.get(top).push(a);
}

const lines = [];
lines.push("# Shortcut check against Logic Pro");
lines.push("");
lines.push("Generated by `tools/gen-shortcut-checklist.mjs` from `ui/actions/actions.json`. Do not edit by hand.");
lines.push("");
lines.push("How to check: in Logic Pro open **Logic Pro > Key Commands > Edit** (or press Option-K), search the command name and");
lines.push("write what Logic shows in the last column. Where it differs, change `shortcut` in `actions.json`, set");
lines.push("`\"verified\": true`, and regenerate this file. `Ctrl` here is Cmd on macOS.");
lines.push("");
lines.push("Rows marked **yes** were confirmed by at least one published source; every other default is a proposal.");
lines.push("");
let total = 0, verified = 0;
for (const [menu, items] of byMenu) {
  lines.push(`## ${menu}`);
  lines.push("");
  lines.push("| Action id | Menu path | Our default | Verified | Logic's default (fill in) |");
  lines.push("|---|---|---|---|---|");
  for (const a of items) {
    total++;
    if (a.verified) verified++;
    lines.push(`| \`${a.id}\` | ${a.menu} > ${a.label} | \`${a.shortcut}\` | ${a.verified ? "**yes**" : "no"} | |`);
  }
  lines.push("");
}
lines.splice(8, 0, `Status: ${verified} of ${total} default shortcuts verified.`, "");
writeFileSync(resolve(root, "docs/shortcuts-check.md"), lines.join("\n"));
console.log(`docs/shortcuts-check.md: ${total} shortcuts, ${verified} verified`);
